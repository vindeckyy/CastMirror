std::string X509NameToStr(X509_NAME* name) {
  if (!name) return "";
  char buf[256] = {0};
  X509_NAME_oneline(name, buf, sizeof(buf) - 1);
  return std::string(buf);
}

std::string ExtractCommonName(X509* cert) {
  if (!cert) return "";
  X509_NAME* subject = X509_get_subject_name(cert);
  if (!subject) return "";
  char cn_buf[256] = {0};
  int idx = X509_NAME_get_text_by_NID(subject, NID_commonName, cn_buf, sizeof(cn_buf) - 1);
  if (idx >= 0) return std::string(cn_buf);
  return "";
}

X509* LoadDerCert(const unsigned char* der, size_t len) {
  const unsigned char* p = der;
  return d2i_X509(nullptr, &p, static_cast<long>(len));
}

